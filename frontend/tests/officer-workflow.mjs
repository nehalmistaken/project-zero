import assert from 'node:assert/strict';
const store=new Map(),session=new Map();
globalThis.localStorage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)};
globalThis.sessionStorage={getItem:k=>session.get(k)||null,setItem:(k,v)=>session.set(k,v),removeItem:k=>session.delete(k)};
const {registerOfficer,loginOfficer,listOfficers,approveOfficer,officerCases,reviewCase}=await import('../src/services/officerAccounts.js');
const {localApi}=await import('../src/services/localApi.js');
await registerOfficer({name:'Review Officer',email:'officer@example.test',department:'Water',username:'waterofficer',password:'test-password-89'});
assert.ok(!store.get('projectzero.officers.v1').includes('test-password-89'));
await assert.rejects(()=>loginOfficer('waterofficer','test-password-89'),/awaiting/);
assert.throws(()=>listOfficers(),/access/);
await loginOfficer('admin','admin123');
approveOfficer(listOfficers()[0].id);
await loginOfficer('waterofficer','test-password-89');
assert.throws(()=>listOfficers(),/access/);
const {complaint}=await localApi.submitComplaint({complaint_text:'A water pipe is leaking on the street',category:'Water'});
assert.equal(officerCases().length,1);
assert.throws(()=>reviewCase(complaint.id,{status:'RESOLVED',priority:'High',remark:'Skipped approval'}),/one stage/);
reviewCase(complaint.id,{status:'ASSIGNED',priority:'High',remark:'Water loss confirmed; dispatch team'});
session.delete('project_officer');
const result=await localApi.getComplaintByGrievanceId(complaint.grievance_id);
assert.equal(result.complaint.priority,'High');assert.equal(result.complaint.status,'ASSIGNED');assert.equal(result.history.length,2);assert.match(result.history[1].remark,/Water loss/);
assert.throws(()=>reviewCase(complaint.id,{status:'IN_PROGRESS',priority:'Low',remark:'Unauthorised change'}),/access/);
console.log('Officer approval, access checks, manual prioritisation and citizen timeline checks passed.');
